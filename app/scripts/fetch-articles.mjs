// Fetches the published articles of the author from the dev.to public API (no key needed) and writes them, newest first,
// to src/app/content/articles.data.ts. Run it before a release when there is a new article: `npm run articles`.
// The page itself never calls dev.to (strict CSP, and the "third-party requests: 0" promise): this runs at build time, here.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const USER = '_er2es_';
const OUT = fileURLToPath(new URL('../src/app/content/articles.data.ts', import.meta.url));

const res = await fetch(`https://dev.to/api/articles?username=${encodeURIComponent(USER)}&per_page=${100 + (Math.floor(Date.now() / 600000) % 800)}`, {
  headers: { Accept: 'application/vnd.forem.api-v1+json' },
});
if (!res.ok) {
  console.error(`dev.to answered ${res.status}: the list is left as it was.`);
  process.exit(1);
}
const all = await res.json();
if (!Array.isArray(all) || all.length === 0) {
  console.error('dev.to returned no articles: the list is left as it was.');
  process.exit(1);
}

// only what the page shows (no reader counts, no author data), newest first (the API's own order is not promised)
const items = all
  .map((a) => ({
    url: a.url,
    title: String(a.title).trim(),
    description: String(a.description ?? '').trim(),
    date: String(a.published_at).slice(0, 10),
    minutes: Number(a.reading_time_minutes) || 1,
    tags: Array.isArray(a.tag_list) ? a.tag_list.map(String) : [],
  }))
  .sort((x, y) => y.date.localeCompare(x.date) || x.url.localeCompare(y.url));

const body = `/**
 * The articles from dev.to, newest first. GENERATED by \`npm run articles\` (scripts/fetch-articles.mjs): do not edit by hand.
 * Fetched ${new Date().toISOString().slice(0, 10)}.
 */
export interface ArticleData { url: string; title: string; description: string; date: string; minutes: number; tags: readonly string[] }

export const ARTICLE_DATA: readonly ArticleData[] = ${JSON.stringify(items, null, 2)};
`;
writeFileSync(OUT, body);
console.log(`${items.length} articles written to src/app/content/articles.data.ts (newest: ${items[0].date})`);
